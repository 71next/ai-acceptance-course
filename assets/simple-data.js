/** 測試案例編號：TC-01 範例、TC-02 半填、之後是學員自己出的題 */
export const caseNo = (i) => `TC-${String(i + 1).padStart(2, '0')}`;

/** 把 ② 的作答整理成案例清單（範例、半填、自出題） */
export function allCases(u2) {
  const half = u2?.half || {};
  const own = (u2?.own || []).filter((c) => c && (c.say || c.expect || c.type));
  return [
    { ...EXAMPLE, id: 'ex', tier: 'example' },
    { ...HALF, id: 'half', tier: 'half', expect: half.expect || '', rules: half.rules || [], pass: half.pass || '' },
    ...own.map((c, i) => ({ ...c, no: caseNo(i + 2), tier: 'own', title: c.title || TYPE_NAME[c.type] || '自行設計' }))
  ];
}
